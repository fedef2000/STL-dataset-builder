"""
Step 7: the final dataset, three sets of (description, formula) pairs in data/dataset/ (src/dataset/sets.py):

    set_1   formula and description from the papers
    set_2   formula from the papers, description written by stl-nl
    set_3   formula and description generated by stl-nl

A judge (two models, a third on their disagreements) says of each description whether it describes its formula and how
faithfully: correct, ambiguous, wrong, or no (it doesn't describe it). One call per formula, with all its descriptions.

    python scripts/07_finalize_dataset.py --judge --trial 20                # set 1: 20 records only, and trial.md
    python scripts/07_finalize_dataset.py --judge --dry-run                 # set 1: the calls a full run would make, and their cost
    python scripts/07_finalize_dataset.py --judge                           # set 1: every record (at most --budget dollars)
    python scripts/07_finalize_dataset.py --judge --set set_2 --sample 200  # 200 formulas of set 2, and set_2_sample.md
    python scripts/07_finalize_dataset.py                                   # the sets from the stored answers: no model is called

Every run ends by writing the three sets from the stored answers:
- set 1 to data/dataset/set_1/, only when every description has a final label (no call missing, no disagreement left
  for the third model): pairs.jsonl (correct), pairs_ambiguous.jsonl, dropped.jsonl (wrong, no, undecided) and
  pairs.xlsx with one sheet each;
- sets 2 and 3 from the stl-nl runs copied by hand into data/dataset/set_N/stlnl_run/ (formulas.jsonl and pairs.jsonl
  of the run): pairs.jsonl with every description, `judge` filled for the formulas judged so far, and pairs.xlsx. A
  set whose stlnl_run/ is missing is skipped.

The answers are kept in data/processed/judgments/answers.jsonl: a run makes only the calls not stored yet, and a
stored answer is asked again only when what the model reads has changed (formula, descriptions, prompt).
"""
import argparse
import collections
import json
import random
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from config import DATA_DIR
from src.dataset.judge import ANSWERS_FILE, paper_items, read_answers, run_calls, stlnl_items, usable, vote
from src.dataset.sets import (DATASET_DIR, SET_1, SET_2, SET_3, STLNL_RUN, attach_judgments, paper_rows, read_jsonl,
                              stlnl_rows, write_set)
from src.extraction.records import DEFAULT_MODELS, DEFAULT_TIE_BREAKER, parse_model

sys.stdout.reconfigure(encoding="utf-8")
PAIRED_RECORDS = DATA_DIR / "normalized" / "paired" / "records.jsonl"
PAIRED_MANIFEST = DATA_DIR / "normalized" / "paired" / "manifest.jsonl"
UNPAIRED_MANIFEST = DATA_DIR / "normalized" / "unpaired" / "manifest.jsonl"
UNPAIRED_RECORDS = DATA_DIR / "extracted" / "unpaired.jsonl"
TRIAL_FILE = ANSWERS_FILE.parent / "trial.md"
MODELS = DEFAULT_MODELS + [DEFAULT_TIE_BREAKER]


def short(label: str) -> str:
    return parse_model(label)[0].split("/")[-1]


def trial_records(records: list[dict], n: int, seed: str = "trial") -> list[dict]:
    """
    n records at random, with some of the cases the judge must handle: a fifth with a generic passage (expected "no")
    and a seventh with several passages (several descriptions in one call); the rest from all records.
    """
    rng = random.Random(seed)
    shuffled = records[:]
    rng.shuffle(shuffled)
    generic = [r for r in shuffled if any(p["kind"] == "generic" for p in r["requirements"])][:max(1, n // 5)]
    several = [r for r in shuffled if len(r["requirements"]) > 1 and r not in generic][:max(1, n // 7)]
    chosen = generic + several
    chosen += [r for r in shuffled if r not in chosen][:n - len(chosen)]
    return sorted(chosen, key=lambda r: r["id"])


def sample_items(items: list[dict], n: int, seed: str = "sample") -> list[dict]:
    """
    n formulas at random. The items are shuffled in a fixed order (by id, then the seed) and the first n taken, so a
    larger n keeps the formulas of a smaller one: their stored answers are used again.
    """
    shuffled = sorted(items, key=lambda i: i["id"])
    random.Random(seed).shuffle(shuffled)
    return sorted(shuffled[:n], key=lambda i: i["id"])


def labels_of(stored: dict, label: str, item: dict) -> list[str | None]:
    """One label per description of the item from one model, None for each when it has no usable answer."""
    row = stored.get((*parse_model(label), item["set"], item["id"]))
    return [j["label"] for j in row["judgments"]] if usable(row, item) else [None] * item["count"]


def judge(items: list[dict], budget: float, workers: int, dry_run: bool) -> dict:
    """The calls of both models, then of the third on the items with a disagreement. Returns the stored answers."""
    first = [(*parse_model(label), item) for label in DEFAULT_MODELS for item in items]
    stored = read_answers()
    if dry_run:
        print_plan(first, stored, len(items))
        return stored
    spent = run_calls(first, workers=workers, budget=budget)
    stored = read_answers()
    disputed = [i for i in items if any(None not in pair and pair[0] != pair[1]
                                        for pair in zip(*(labels_of(stored, l, i) for l in DEFAULT_MODELS)))]
    print(f"\nThe third model ({short(DEFAULT_TIE_BREAKER)}) on the {len(disputed)} formulas where the two differ:")
    run_calls([(*parse_model(DEFAULT_TIE_BREAKER), item) for item in disputed], workers=workers, budget=budget - spent)
    return read_answers()


def print_plan(tasks: list[tuple], stored: dict, n_items: int):
    """
    --dry-run: the calls still to make per model, priced at the average of all the stored calls of that model (of any
    set), the third model on the share of formulas it was asked about so far.
    """
    print(f"{n_items} formulas to judge")
    total = 0.0
    first_calls = sum(1 for k, r in stored.items() if k[:2] == parse_model(DEFAULT_MODELS[0]) and r.get("judgments"))
    for label in MODELS:
        model, reasoning = parse_model(label)
        costs = [r["cost"] for k, r in stored.items() if k[:2] == (model, reasoning) and r.get("judgments")]
        if label == DEFAULT_TIE_BREAKER:
            share = len(costs) / max(1, first_calls)
            todo = round(n_items * share)
            note = f" (on {share:.0%} of the formulas, as in the stored answers)"
        else:
            todo = sum(1 for m, r, item in tasks if (m, r) == (model, reasoning) and not usable(stored.get((m, r, item["set"], item["id"])), item))
            note = ""
        each = sum(costs) / len(costs) if costs else None
        price = f"about ${each * todo:.2f}" if each is not None else "cost unknown: no stored answer to price it (run --trial first)"
        total += each * todo if each is not None else 0
        print(f"  {short(label):<24} {todo:>6} calls   {price}{note}")
    print(f"  {'total':<24}               about ${total:.2f}")


def summary(items: list[dict], stored: dict) -> list[dict]:
    """Prints the cost of each model and the final labels; returns one row per description, for the review file."""
    rows = []
    for item in items:
        first = [labels_of(stored, label, item) for label in DEFAULT_MODELS]
        third = labels_of(stored, DEFAULT_TIE_BREAKER, item)
        for n in range(item["count"]):
            final, how = vote([first[0][n], first[1][n]], third[n])
            rows.append({"item": item, "n": n, "labels": [first[0][n], first[1][n], third[n]], "final": final, "how": how})
    print("\nCalls per model:")
    for label in MODELS:
        model, reasoning = parse_model(label)
        # Only answers to the items as they are now (an answer to an older prompt doesn't count)
        answers = [row for i in items if (row := stored.get((model, reasoning, i["set"], i["id"]))) and row["key"] == i["key"]]
        cost = sum(a.get("cost", 0) for a in answers)
        failed = sum(1 for a in answers if not a.get("judgments"))
        seconds = [a["seconds"] for a in answers if "seconds" in a]
        print(f"  {short(label):<24} {len(answers):>5} calls  {failed:>3} failed  ${cost:.4f} (${cost / max(1, len(answers)):.5f} per call)"
              + (f"  {sum(seconds) / len(seconds):.1f} s per call" if seconds else ""))
    agreed = sum(1 for r in rows if r["how"] == "agreed")
    print(f"\nThe first two models agree on {agreed} of {len(rows)} descriptions ({agreed / max(1, len(rows)):.0%}).")
    print("Final labels:")
    for label, count in collections.Counter(r["final"] for r in rows).most_common():
        print(f"  {label:<12} {count:>5}")
    return rows


def write_review(rows: list[dict], stored: dict, path: Path, title: str):
    """Each description judged, with its formula, the label and the problems each model gave (trial.md, set_N_sample.md)."""
    out = [f"# {title}", "",
           "| Formula | D | Kind | " + " | ".join(short(m) for m in MODELS) + " | Final |",
           "|---|---|---|" + "---|" * len(MODELS) + "---|"]
    for r in rows:
        item = r["item"]
        out.append(f"| {item['id']} | D{r['n'] + 1} | {item['kinds'][r['n']] or ''} | "
                   + " | ".join(l or "" for l in r["labels"]) + f" | **{r['final']}** |")
    for r in rows:
        item = r["item"]
        kind = item["kinds"][r["n"]]
        out += ["", f"## {item['id']} D{r['n'] + 1}: {r['final']} ({r['how']})", "",
                f"- Formula: `{item['formula']}`", f"- Description{f' ({kind})' if kind else ''}: {item['descriptions'][r['n']]}", ""]
        for label in MODELS:
            row = stored.get((*parse_model(label), item["set"], item["id"]))
            if not usable(row, item):
                continue
            j = row["judgments"][r["n"]]
            out.append(f"- **{short(label)}: {j['label']}**: {j['reason']}" + "".join(f"\n    - {p}" for p in j["problems"]))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"\nEvery answer: {path}")


def stlnl_set_rows(name: str) -> tuple[list[dict], dict] | None:
    """The rows of set 2 or 3 from its stl-nl run, not judged; None (and a message) when the run isn't copied."""
    run = DATASET_DIR / name / STLNL_RUN
    missing = [f for f in ("formulas.jsonl", "pairs.jsonl") if not (run / f).exists()]
    if missing:
        print(f"\n{name} skipped: {', '.join(missing)} not in {run.relative_to(BASE_DIR)}/")
        return None
    if name == SET_2:
        records = {r["id"]: r for r in read_jsonl(UNPAIRED_RECORDS)}
        return stlnl_rows(name, run, read_jsonl(UNPAIRED_MANIFEST), records)
    return stlnl_rows(name, run)


def written(name: str, counts: dict[str, int], note: str = ""):
    print(f"\nWritten data/dataset/{name}/: " + ", ".join(f"{part}.jsonl {n}" for part, n in counts.items()) + ", pairs.xlsx" + note)


def write_sets(records: list[dict], stored: dict):
    """The three sets from the stored answers."""
    items = paper_items(records)
    labels = [vote([labels_of(stored, l, i)[n] for l in DEFAULT_MODELS], labels_of(stored, DEFAULT_TIE_BREAKER, i)[n])[0]
              for i in items for n in range(i["count"])]
    pending = sum(1 for label in labels if label in ("unjudged", "disputed"))
    if pending:
        print(f"\n{SET_1} not written: {pending} descriptions have no final label yet (run with --judge)")
    else:
        names = {line["id"]: [p["names_not_in_formula"] for p in line["requirements"]]
                 for line in read_jsonl(PAIRED_MANIFEST) if line["status"] == "ok"}
        written(SET_1, write_set(paper_rows(records, items, stored, DEFAULT_MODELS, DEFAULT_TIE_BREAKER, names), DATASET_DIR / SET_1))
    for name in (SET_2, SET_3):
        built = stlnl_set_rows(name)
        if built is None:
            continue
        rows, counts = built
        judged = attach_judgments(rows, stlnl_items(rows), stored, DEFAULT_MODELS, DEFAULT_TIE_BREAKER)
        written(name, write_set(rows, DATASET_DIR / name), f" ({judged} descriptions judged)")
        for what, n in counts.items():
            print(f"   {n:>6}  {what}")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--judge", action="store_true", help="judge the descriptions of --set (calls the models), then write the sets")
    parser.add_argument("--set", default=SET_1, choices=(SET_1, SET_2, SET_3), help="the set to judge (default set_1)")
    parser.add_argument("--trial", type=int, metavar="N", help="set 1: only N records, and write trial.md with every answer")
    parser.add_argument("--sample", type=int, metavar="N", help="sets 2 and 3: only N formulas, and write set_N_sample.md with every answer")
    parser.add_argument("--dry-run", action="store_true", help="only print the calls a run would make and their cost")
    parser.add_argument("--budget", type=float, default=10.0, help="dollars after which no new call is started (default 10)")
    parser.add_argument("--workers", type=int, default=8, help="calls made at the same time (default 8)")
    args = parser.parse_args()
    if not args.judge and (args.trial or args.sample or args.dry_run):
        parser.error("--trial, --sample and --dry-run go with --judge")
    if args.trial and args.set != SET_1:
        parser.error("--trial is for set 1 (it picks generic passages); use --sample for sets 2 and 3")
    if args.sample and args.set == SET_1:
        parser.error("--sample is for sets 2 and 3; use --trial for set 1")

    records = read_jsonl(PAIRED_RECORDS)
    stored = read_answers()
    if args.judge:
        if args.set == SET_1:
            items = paper_items(trial_records(records, args.trial) if args.trial else records)
        else:
            built = stlnl_set_rows(args.set)
            if built is None:
                return
            items = stlnl_items(built[0])
            items = sample_items(items, args.sample) if args.sample else items
        stored = judge(items, args.budget, args.workers, args.dry_run)
        if args.dry_run:
            return
        rows = summary(items, stored)
        if args.trial:
            write_review(rows, stored, TRIAL_FILE, "Judge trial")
            return
        if args.sample:
            write_review(rows, stored, ANSWERS_FILE.parent / f"{args.set}_sample.md", f"Judge sample of {args.set}")
    write_sets(records, stored)


if __name__ == "__main__":
    main()
