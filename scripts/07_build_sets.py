"""
Step 7: the three sets of (description, formula) pairs of the dataset in data/dataset/ (src/dataset/sets.py). No
model is called.

    set_1   formula and description from the papers
    set_2   formula from the papers, description written by stl-nl
    set_3   formula and description generated by stl-nl

    python scripts/07_build_sets.py

- set 1: every description of the papers (data/normalized/paired/records.jsonl) to data/dataset/set_1/candidates.jsonl.
  They are candidates: the round trip of step 8 keeps those a model can write back into their formula
  (set_1/pairs.jsonl) and drops the others (set_1/dropped.jsonl). The formulas fixed by hand
  (data/dataset/set_1/manual.jsonl, src/dataset/manual.py) are replaced here, so that step 8 checks the new formula;
  keep and drop are applied by step 8.
- sets 2 and 3: from the stl-nl runs copied by hand into data/dataset/set_N/stlnl_run/ (formulas.jsonl and
  pairs.jsonl of the run): pairs.jsonl with every description, and pairs2.xlsx or pairs3.xlsx. A set whose
  stlnl_run/ is missing is skipped.
The pairs whose formula writes X (next, not standard STL) are left out of every set (sets.without_next).

Then: python scripts/08_roundtrip.py (the round trip, which splits set 1 and writes analysis.md), then
python scripts/09_augment_dataset.py (the paraphrases) and python scripts/08_roundtrip.py again (which checks them).
"""
import argparse
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR))

from config import DATA_DIR
from src.dataset.manual import MANUAL_FILE, apply_decisions, read_decisions
from src.dataset.sets import (DATASET_DIR, SET_1, SET_2, SET_3, STLNL_RUN, XLSX_NAME, paper_rows, read_jsonl, stlnl_rows,
                              without_next, write_candidates, write_set)
from src.evaluation.stlgen import parse_many

sys.stdout.reconfigure(encoding="utf-8")
PAIRED_RECORDS = DATA_DIR / "normalized" / "paired" / "records.jsonl"
PAIRED_MANIFEST = DATA_DIR / "normalized" / "paired" / "manifest.jsonl"
UNPAIRED_MANIFEST = DATA_DIR / "normalized" / "unpaired" / "manifest.jsonl"
UNPAIRED_RECORDS = DATA_DIR / "extracted" / "unpaired.jsonl"


def stlnl_set_rows(name: str) -> tuple[list[dict], dict] | None:
    """The rows of set 2 or 3 from its stl-nl run; None (and a message) when the run isn't copied."""
    run = DATASET_DIR / name / STLNL_RUN
    missing = [f for f in ("formulas.jsonl", "pairs.jsonl") if not (run / f).exists()]
    if missing:
        print(f"\n{name} skipped: {', '.join(missing)} not in {run.relative_to(BASE_DIR)}/")
        return None
    if name == SET_2:
        records = {r["id"]: r for r in read_jsonl(UNPAIRED_RECORDS)}
        return stlnl_rows(name, run, read_jsonl(UNPAIRED_MANIFEST), records)
    return stlnl_rows(name, run)


def written(name: str, counts: dict[str, int], note: str = "", left_out: int = 0):
    print(f"\nWritten data/dataset/{name}/: " + ", ".join(f"{part}.jsonl {n}" for part, n in counts.items()) + note)
    if left_out:
        print(f"   {left_out:>6}  descriptions left out: their formula uses X (next), not standard STL")


def write_sets(records: list[dict]):
    names = {line["id"]: [p["names_not_in_formula"] for p in line["requirements"]]
             for line in read_jsonl(PAIRED_MANIFEST) if line["status"] == "ok"}
    rows, left_out = without_next(paper_rows(records, names))
    decisions = read_decisions()
    trees = parse_many({d["stl"]: d["stl"] for d in decisions.values() if d["action"] == "fix"})
    rows, by_hand, warnings = apply_decisions(rows, decisions, trees)
    written(SET_1, write_candidates(rows, DATASET_DIR / SET_1), left_out=left_out)
    if decisions:
        print(f"   by hand ({MANUAL_FILE.relative_to(BASE_DIR)}): " + ", ".join(f"{a} {n}" for a, n in by_hand.items())
              + " (only fix changes the candidates; keep and drop are applied by step 8)")
    for warning in warnings:
        print(f"   WARNING {warning}")
    for name in (SET_2, SET_3):
        built = stlnl_set_rows(name)
        if built is None:
            continue
        rows, counts = built
        rows, left_out = without_next(rows)
        written(name, write_set(rows, DATASET_DIR / name), f", {XLSX_NAME[name]}", left_out)
        for what, n in counts.items():
            print(f"   {n:>6}  {what}")
    print("\nNext: python scripts/08_roundtrip.py (splits set 1's candidates, writes analysis.md)")


def main():
    argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter).parse_args()
    write_sets(read_jsonl(PAIRED_RECORDS))


if __name__ == "__main__":
    main()
