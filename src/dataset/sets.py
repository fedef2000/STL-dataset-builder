"""
The sets of the final dataset (data/dataset/), one folder each:

    set_1   formula and description from the papers (data/normalized/paired/records.jsonl)
    set_2   formula from the papers (data/normalized/unpaired/stl/), description written by stl-nl
    set_3   formula and description generated by stl-nl

Set 1 is written in two steps. Step 7 writes every description of the papers to candidates.jsonl; step 8, the round
trip, splits the candidates into pairs.jsonl (in the dataset) and dropped.jsonl (split, below), and writes
pairs1.xlsx. The paraphrases of step 9 (set_1/augmented/) go the same way: candidates.jsonl, then pairs.jsonl and
dropped.jsonl. Sets 2 and 3 are written by step 7 whole: pairs.jsonl (every description) and the xlsx.

The runs of stl-nl are copied by hand into set_2/stlnl_run/ and set_3/stlnl_run/: its formulas.jsonl (the formulas,
with their AST) and pairs.jsonl (the descriptions). Every set is written as rows of one schema, one row per
(description, formula) pair:

    id            the pair: <record id>:D<n> (set 1), <record id>:R<n> (set 2), stlnl_<source index>:R<n> (set 3)
    set           the folder name
    nl, stl       the description and the formula; stl is written as stl-nl prints it (emit.stlnl_text for set 1,
                  stl-nl's own text for sets 2 and 3), so the three sets write their formulas alike
    formula_id    the formula: the record id of step 5 for paper formulas, stlnl_<source index> for set 3
    stlnl_formula_id   stl-nl's id of the formula (a hash of its AST; sets 2 and 3)
    template       as in step 6 (sets 1 and 2; null for set 3), pattern: as in step 6, from the AST for sets 2 and 3
    roundtrip     what the round trip of step 8 says of the pair: verdict (match: at least one of the two models
                  wrote the formula back from the description; miss: neither did; not_checkable: stlgen can't read
                  the formula) and best (the closest level of the two answers); null until step 8 has checked it
    dropped       why the pair is out of the dataset (dropped.jsonl only)
    signals       checks made without a model, recorded only: names of the description the formula doesn't have
                  (set 1 only, from step 6)
    original_stl, original_nl   as the paper writes them (LaTeX), for checking (original_nl: set 1 only)
    kind, domain, paper_id, license_tier, license, source_type   from step 5 (set 3: only domain, from stl-nl)
    stlnl_pattern_id   the property pattern of stl-nl's generator the formula comes from (bounded_response, invariance,
                       ...; set 3), stl-nl's own name: not the pattern of the field `pattern`
"""
import collections
import json
import re
from pathlib import Path

from config import DATA_DIR
from src.normalization.pattern import pattern

DATASET_DIR = DATA_DIR / "dataset"
SET_1, SET_2, SET_3 = "set_1", "set_2", "set_3"
# The xlsx of each set, with the number of the set in its name, so that the files opened side by side are told apart
XLSX_NAME = {SET_1: "pairs1.xlsx", SET_2: "pairs2.xlsx", SET_3: "pairs3.xlsx"}
STLNL_RUN = "stlnl_run"   # the folder of a set where the files of its stl-nl run are copied
def paper_rows(records: list[dict], names_not_in_formula: dict[str, list[list[str]]]) -> list[dict]:
    """
    Set 1: one row per requirement passage of the paired records, every one a candidate.
    `names_not_in_formula`: record id -> per passage, the names step 6 found (they are in its manifest only).
    """
    rows = []
    for r in records:
        names = names_not_in_formula.get(r["id"]) or [[] for _ in r["requirements"]]
        for n, passage in enumerate(r["requirements"]):
            rows.append({
                "id": f"{r['id']}:D{n + 1}", "set": SET_1, "nl": passage["normalized"], "stl": r["stl"],
                "formula_id": r["id"], "stlnl_formula_id": None, "template": r["template"], "pattern": r["pattern"],
                "roundtrip": None,
                "signals": {"names_not_in_formula": names[n]},
                "original_stl": r["formula"], "original_nl": passage["text"], "kind": passage["kind"],
                "domain": r.get("domain"), "paper_id": r["paper_id"], "license_tier": r.get("license_tier"),
                "license": r.get("license"), "source_type": r.get("source_type"), "stlnl_pattern_id": None,
            })
    return rows


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in open(path, encoding="utf-8") if line.strip()]


def stlnl_rows(name: str, run: Path, manifest: list[dict] | None = None, records: dict[str, dict] | None = None) -> tuple[list[dict], dict]:
    """
    Set 2 or 3: one row per description of an stl-nl run (`run`: its formulas.jsonl and pairs.jsonl).
    For set 2, `manifest` (data/normalized/unpaired/manifest.jsonl) and `records` (data/extracted/unpaired.jsonl by
    id) link each formula to its paper: through the .stl file it was read from, checked to hold the same text.
    Returns the rows and what the conversion counted (formulas without a description, formulas not linked).
    """
    formulas = read_jsonl(run / "formulas.jsonl")
    pairs = collections.defaultdict(list)
    for pair in read_jsonl(run / "pairs.jsonl"):
        pairs[pair["formula_id"]].append(pair)
    by_file = {Path(line["file"]).name: line for line in manifest or [] if line.get("file")}   # "stl/f00001.stl"
    counts = collections.Counter(formulas=len(formulas))
    rows = []
    for f in formulas:
        described = sorted(pairs.get(f["formula_id"], []), key=lambda p: p["realization_index"])
        if not described:
            counts["formulas without a description (failed in the stl-nl run, or not reached by it)"] += 1
            continue
        source = f["source"]
        pattern_text, _ = pattern(f["ast"])
        row = {"set": name, "stl": f["stl"], "formula_id": f"stlnl_{source['source_index']}",
               "stlnl_formula_id": f["formula_id"], "template": None, "pattern": pattern_text, "roundtrip": None,
               "original_stl": None, "original_nl": None, "kind": None, "domain": source.get("domain"),
               "paper_id": None, "license_tier": None, "license": None, "source_type": None,
               "stlnl_pattern_id": source.get("pattern_id")}
        if manifest is not None:
            line = by_file.get(Path(source.get("path") or "").name)
            if line is None or line["normalized"].strip() != (source.get("source_text") or "").strip():
                counts["formulas not linked to a paper (no .stl file of step 6 with the same text)"] += 1
            else:
                record = records[line["id"]]
                row.update(formula_id=line["id"], template=line["template"], original_stl=line["original"],
                           domain=record.get("domain"), paper_id=record["paper_id"], license_tier=record.get("license_tier"),
                           license=record.get("license"), source_type=record.get("source_type"))
        for pair in described:
            rows.append({"id": f"{row['formula_id']}:R{pair['realization_index']}", "nl": pair["nl"], **row,
                         "signals": {"names_not_in_formula": None}})
    counts["descriptions"] = len(rows)
    return rows, counts


# X (next) is not standard STL (it belongs to discrete time and LTL), so a model trained on the dataset shouldn't learn
# to write it: the pairs whose formula `stl` writes it are left out of every set. Only set 1 has them: in sets 2 and 3
# stl-nl writes the X of a paper formula as F[1,1], and its descriptions follow that (those pairs stay). X is the
# operator when ( or a space and its operand follow it (X G[0,5] !red, X (l == normal)); a name starting with X (XXS,
# XMEAS_21) goes on with a letter or digit, and a signal named X is followed by a comparison (X != 3, X > 1).
NEXT_OPERATOR = re.compile(r"(?<![\w])X(?=\(|\s+(?:[(A-Za-z]|!(?!=)))")


def without_next(rows: list[dict]) -> tuple[list[dict], int]:
    """The rows whose formula doesn't write X, and how many were left out."""
    kept = [r for r in rows if not NEXT_OPERATOR.search(r["stl"])]
    return kept, len(rows) - len(kept)


def write_jsonl(rows: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as out:
        out.writelines(json.dumps(r, ensure_ascii=False) + "\n" for r in rows)


def write_set(rows: list[dict], folder: Path) -> dict[str, int]:
    """Set 2 or 3: pairs.jsonl with every row, and the xlsx (XLSX_NAME). Returns the rows per file."""
    write_jsonl(rows, folder / "pairs.jsonl")
    write_xlsx(folder / XLSX_NAME[folder.name], {"pairs": rows})
    return {"pairs": len(rows)}


def write_candidates(rows: list[dict], folder: Path) -> dict[str, int]:
    """Set 1 (step 7) or its paraphrases (step 9): candidates.jsonl, every row, for the round trip to split."""
    write_jsonl(rows, folder / "candidates.jsonl")
    return {"candidates": len(rows)}


# Why a candidate is out of the dataset (the field `dropped`)
BY_HAND = "by hand"
BOTH_MISS = "round trip: neither model wrote the formula back"
NOT_CHECKABLE = "round trip: not checkable (stlgen can't read the formula)"
ORIGINAL_OUT = "its original is not in the dataset"
NO_ANSWER = "round trip: no answer yet"
SHORT_REASONS = {BY_HAND: "dropped by hand", BOTH_MISS: "both miss", NOT_CHECKABLE: "not checkable",
                 ORIGINAL_OUT: "original out", NO_ANSWER: "no answer yet"}


def short_reason(dropped: str) -> str:
    """The reason of a dropped row in a few words, for the tables (a decision by hand carries its note after ':')."""
    return SHORT_REASONS[BY_HAND if dropped.startswith(BY_HAND) else dropped]


def split(rows: list[dict], verdicts: dict[str, dict], decisions: dict[str, dict],
          originals: set[str] | None = None) -> tuple[list[dict], list[dict]]:
    """
    The candidates of set 1 (or its paraphrases) split into the dataset (pairs) and out of it (dropped), in this order:

        drop by hand                           dropped
        a paraphrase whose original is out     dropped   (only with `originals`: the ids of set 1's pairs)
        keep or fix by hand                    pairs
        round trip: match                      pairs     (at least one of the two models wrote the formula back)
        round trip: miss, not_checkable        dropped

    `verdicts`: id -> {"verdict", "best"} from the round trip (src/evaluation/roundtrip.py, verdict). `decisions`: the
    lines of manual.jsonl by id. Every row gets `roundtrip` (its verdict, None when the round trip has none: dropped
    by hand) and `manual` (its decision, when there is one); a dropped row gets `dropped`, why.
    """
    pairs, dropped = [], []
    for row in rows:
        row = {k: v for k, v in row.items() if k not in ("manual", "dropped")}
        row["roundtrip"] = verdicts.get(row["id"])
        decision = decisions.get(row["id"])
        if decision:
            row["manual"] = {k: v for k, v in decision.items() if k != "id"}
        action = decision["action"] if decision else None
        if action == "drop":
            why = f"{BY_HAND}: {decision['note']}" if decision["note"] else BY_HAND
        elif originals is not None and row.get("augmented_from") not in originals:
            why = ORIGINAL_OUT
        elif action in ("keep", "fix"):
            why = None
        elif row["roundtrip"] is None:
            why = NO_ANSWER
        else:
            why = {"match": None, "miss": BOTH_MISS, "not_checkable": NOT_CHECKABLE}[row["roundtrip"]["verdict"]]
        if why is None:
            pairs.append(row)
        else:
            dropped.append({**row, "dropped": why})
    return pairs, dropped


def write_split(pairs: list[dict], dropped: list[dict], folder: Path, xlsx: bool = True) -> dict[str, int]:
    """pairs.jsonl and dropped.jsonl of a split, and (set 1) the xlsx with one sheet each. Returns the rows per file."""
    write_jsonl(pairs, folder / "pairs.jsonl")
    write_jsonl(dropped, folder / "dropped.jsonl")
    if xlsx:
        write_xlsx(folder / XLSX_NAME[folder.name], {"pairs": pairs, "dropped": dropped})
    return {"pairs": len(pairs), "dropped": len(dropped)}


# ---------------------------------------------------------------- the xlsx file, to check the pairs by eye

COLUMNS = [  # (header, width, value of a row)
    ("id", 24, lambda r: r["id"]),
    ("stl", 50, lambda r: r["stl"]),
    ("nl", 60, lambda r: r["nl"]),
    ("round trip", 16, lambda r: f"{r['roundtrip']['verdict']} ({r['roundtrip']['best']})" if r.get("roundtrip") else ""),
    ("why dropped", 40, lambda r: r.get("dropped") or ""),
    ("by hand", 30, lambda r: (f"{r['manual']['action']}: {r['manual']['note']}"
                               + (f"\n(was {r['stl_before_fix']})" if r.get("stl_before_fix") else "")) if r.get("manual") else ""),
    ("kind", 10, lambda r: r.get("kind") or ""),
    ("original stl", 45, lambda r: r.get("original_stl") or ""),
    ("original nl", 60, lambda r: r.get("original_nl") or ""),
    ("domain", 16, lambda r: r.get("domain") or ""),
    ("license tier", 16, lambda r: r.get("license_tier") or ""),
]
ILLEGAL_XML = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")


def write_xlsx(path: Path, sheets: dict[str, list[dict]]):
    """
    One sheet per part, with a frozen header, filters on every column and wrapped text. The columns "by hand" and
    "why dropped" only when some row has something in them, "round trip" only when some row has been checked.
    """
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font
    from openpyxl.utils import get_column_letter

    book = Workbook()
    book.remove(book.active)
    wrap = Alignment(wrap_text=True, vertical="top")
    every = [r for rows in sheets.values() for r in rows]
    shown = {"by hand": any(r.get("manual") for r in every), "why dropped": any(r.get("dropped") for r in every),
             "round trip": any(r.get("roundtrip") for r in every)}
    columns = [c for c in COLUMNS if shown.get(c[0], True)]
    for title, rows in sheets.items():
        sheet = book.create_sheet(title)
        sheet.append([header for header, _, _ in columns])
        for cell in sheet[1]:
            cell.font = Font(bold=True)
        for r in rows:
            sheet.append([ILLEGAL_XML.sub("", str(value(r))) for _, _, value in columns])
        for i, (_, width, _) in enumerate(columns, 1):
            sheet.column_dimensions[get_column_letter(i)].width = width
        for row in sheet.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = wrap
        sheet.freeze_panes = "B2"
        sheet.auto_filter.ref = sheet.dimensions
    book.save(path)
