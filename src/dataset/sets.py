"""
The sets of the final dataset (data/dataset/), one folder each:

    set_1   formula and description from the papers (data/normalized/paired/records.jsonl), judged
    set_2   formula from the papers (data/normalized/unpaired/stl/), description written by stl-nl
    set_3   formula and description generated by stl-nl

The runs of stl-nl are copied by hand into set_2/stlnl_run/ and set_3/stlnl_run/: its formulas.jsonl (the formulas,
with their AST) and pairs.jsonl (the descriptions). Every set is written as rows of one schema, one row per
(description, formula) pair:

    id            the pair: <record id>:D<n> (set 1), <record id>:R<n> (set 2), stlnl_<source index>:R<n> (set 3)
    set           the folder name
    nl, stl       the description and the formula; stl is written as stl-nl prints it (emit.stlnl_text for set 1,
                  stl-nl's own text for sets 2 and 3), so the three sets write their formulas alike
    formula_id    the formula: the record id of step 5 for paper formulas, stlnl_<source index> for set 3
    stlnl_formula_id   stl-nl's id of the formula (a hash of its AST; sets 2 and 3)
    pattern       as in step 6 (sets 1 and 2; null for set 3), skeleton: as in step 6, from the AST for sets 2 and 3
    judge         the final label (correct, ambiguous, wrong, no, undecided), how it was reached, and each model's
                  answer; null while the set isn't judged
    signals       checks made without a model, recorded only: numbers of the formula the description doesn't state,
                  names of the description the formula doesn't have (set 1 only, from step 6)
    original_stl, original_nl   as the paper writes them (LaTeX), for checking (original_nl: set 1 only)
    kind, domain, paper_id, license_tier, license, source_type   from step 5 (set 3: only domain, from stl-nl)
    stlnl_pattern_id   the pattern stl-nl generated the formula from (set 3)
"""
import collections
import json
import re
from pathlib import Path

from config import DATA_DIR
from src.dataset.judge import usable, vote
from src.extraction.records import parse_model
from src.normalization.skeleton import skeleton

DATASET_DIR = DATA_DIR / "dataset"
SET_1, SET_2, SET_3 = "set_1", "set_2", "set_3"
STLNL_RUN = "stlnl_run"   # the folder of a set where the files of its stl-nl run are copied
NUMBER = re.compile(r"(?<![\w.])-?\d+(?:\.\d+)?(?![\w.])")
# In a description a unit may follow the number with no space: 30.85m, 200ms
NL_NUMBER = re.compile(r"(?<![\w.])-?\d+(?:\.\d+)?(?!\d|\.\d)")
NUMBER_WORDS = {"zero": "0", "one": "1", "two": "2", "three": "3", "four": "4", "five": "5", "six": "6", "seven": "7",
                "eight": "8", "nine": "9", "ten": "10", "eleven": "11", "twelve": "12", "fifteen": "15", "twenty": "20",
                "thirty": "30", "sixty": "60", "hundred": "100"}


def numbers_missing(stl: str, nl: str) -> list[str]:
    """
    The numbers of the formula (bounds, thresholds) the description doesn't state, as digits or as a word up to
    twenty and a few round ones ("two seconds" states 2), compared as values. 0 is left out: a lower bound 0 is "from now" in words.
    """
    stated = set(NL_NUMBER.findall(nl)) | {digit for word, digit in NUMBER_WORDS.items() if re.search(rf"\b{word}\b", nl, re.I)}
    values = {abs(float(n)) for n in stated}   # compared as values: 3.0 states 3, 11.10 states 11.1
    out = []
    for n in NUMBER.findall(stl):
        n = n.lstrip("-")
        if float(n) != 0 and float(n) not in values and n not in out:
            out.append(n)
    return out


def final_judgment(stored: dict, item: dict, n: int, models: list[str], tie_breaker: str) -> dict:
    """The final label of description n of an item, how it was reached, and each model's answer to it."""
    answers, labels = [], {}
    for label in models + [tie_breaker]:
        row = stored.get((*parse_model(label), item["set"], item["id"]))
        if usable(row, item):
            j = row["judgments"][n]
            labels[label] = j["label"]
            answers.append({"model": label, "label": j["label"], "reason": j["reason"], "problems": j["problems"]})
    final, how = vote([labels.get(m) for m in models], labels.get(tie_breaker))
    return {"label": final, "how": how, "answers": answers}


def paper_rows(records: list[dict], items: list[dict], stored: dict, models: list[str], tie_breaker: str,
               names_not_in_formula: dict[str, list[list[str]]]) -> list[dict]:
    """
    Set 1: one row per requirement passage of the paired records, with the judge's final label.
    `names_not_in_formula`: record id -> per passage, the names step 6 found (they are in its manifest only).
    """
    rows = []
    by_id = {item["id"]: item for item in items}
    for r in records:
        names = names_not_in_formula.get(r["id"]) or [[] for _ in r["requirements"]]
        for n, passage in enumerate(r["requirements"]):
            rows.append({
                "id": f"{r['id']}:D{n + 1}", "set": SET_1, "nl": passage["normalized"], "stl": r["stl"],
                "formula_id": r["id"], "stlnl_formula_id": None, "pattern": r["pattern"], "skeleton": r["skeleton"],
                "judge": final_judgment(stored, by_id[r["id"]], n, models, tie_breaker),
                "signals": {"numbers_missing": numbers_missing(r["stl"], passage["normalized"]),
                            "names_not_in_formula": names[n]},
                "original_stl": r["formula"], "original_nl": passage["text"], "kind": passage["kind"],
                "domain": r.get("domain"), "paper_id": r["paper_id"], "license_tier": r.get("license_tier"),
                "license": r.get("license"), "source_type": r.get("source_type"), "stlnl_pattern_id": None,
            })
    return rows


def read_jsonl(path: Path) -> list[dict]:
    return [json.loads(line) for line in open(path, encoding="utf-8") if line.strip()]


def stlnl_rows(name: str, run: Path, manifest: list[dict] | None = None, records: dict[str, dict] | None = None) -> tuple[list[dict], dict]:
    """
    Set 2 or 3: one row per description of an stl-nl run (`run`: its formulas.jsonl and pairs.jsonl), not judged.
    For set 2, `manifest` (data/normalized/unpaired/manifest.jsonl) and `records` (data/extracted/unpaired.jsonl by
    id) link each formula to its paper: through the .stl file it was read from, checked to hold the same text.
    Returns the rows and what the conversion counted (formulas without a description, formulas not linked).
    """
    formulas = read_jsonl(run / "formulas.jsonl")
    pairs = collections.defaultdict(list)
    for pair in read_jsonl(run / "pairs.jsonl"):
        pairs[pair["formula_id"]].append(pair)
    by_file = {Path(line["file"]).name: line for line in manifest or [] if line.get("file")}   # "stl/f00001.stl"
    counts = collections.Counter(formulas=len(formulas))
    rows = []
    for f in formulas:
        described = sorted(pairs.get(f["formula_id"], []), key=lambda p: p["realization_index"])
        if not described:
            counts["formulas without a description (failed in the stl-nl run, or not reached by it)"] += 1
            continue
        source = f["source"]
        skeleton_text, _ = skeleton(f["ast"])
        row = {"set": name, "stl": f["stl"], "formula_id": f"stlnl_{source['source_index']}",
               "stlnl_formula_id": f["formula_id"], "pattern": None, "skeleton": skeleton_text, "judge": None,
               "original_stl": None, "original_nl": None, "kind": None, "domain": source.get("domain"),
               "paper_id": None, "license_tier": None, "license": None, "source_type": None,
               "stlnl_pattern_id": source.get("pattern_id")}
        if manifest is not None:
            line = by_file.get(Path(source.get("path") or "").name)
            if line is None or line["normalized"].strip() != (source.get("source_text") or "").strip():
                counts["formulas not linked to a paper (no .stl file of step 6 with the same text)"] += 1
            else:
                record = records[line["id"]]
                row.update(formula_id=line["id"], pattern=line["pattern"], original_stl=line["original"],
                           domain=record.get("domain"), paper_id=record["paper_id"], license_tier=record.get("license_tier"),
                           license=record.get("license"), source_type=record.get("source_type"))
        for pair in described:
            rows.append({"id": f"{row['formula_id']}:R{pair['realization_index']}", "nl": pair["nl"], **row,
                         "signals": {"numbers_missing": numbers_missing(f["stl"], pair["nl"]), "names_not_in_formula": None}})
    counts["descriptions"] = len(rows)
    return rows, counts


# The files of a set: the label of the pairs that go in each
SPLIT = {"pairs": ("correct",), "pairs_ambiguous": ("ambiguous",), "dropped": ("wrong", "no", "undecided")}


def write_set(rows: list[dict], folder: Path) -> dict[str, int]:
    """
    A judged set: pairs.jsonl, pairs_ambiguous.jsonl, dropped.jsonl, and pairs.xlsx with one sheet each. A set not
    judged yet: pairs.jsonl with every row, and pairs.xlsx with one sheet. Returns the rows per file.
    """
    folder.mkdir(parents=True, exist_ok=True)
    if any(r["judge"] is None for r in rows):
        parts = {"pairs": rows}
        sheets = {"pairs": rows}
    else:
        parts = {name: [r for r in rows if r["judge"]["label"] in labels] for name, labels in SPLIT.items()}
        sheets = {"pairs": parts["pairs"], "ambiguous": parts["pairs_ambiguous"], "dropped": parts["dropped"]}
    for name, part in parts.items():
        with open(folder / f"{name}.jsonl", "w", encoding="utf-8") as out:
            for r in part:
                out.write(json.dumps(r, ensure_ascii=False) + "\n")
    write_xlsx(folder / "pairs.xlsx", sheets)
    return {name: len(part) for name, part in parts.items()}


# ---------------------------------------------------------------- the xlsx file, to check the pairs by eye

COLUMNS = [  # (header, width, value of a row)
    ("id", 24, lambda r: r["id"]),
    ("stl", 50, lambda r: r["stl"]),
    ("nl", 60, lambda r: r["nl"]),
    ("label", 11, lambda r: r["judge"]["label"]),
    ("how", 18, lambda r: r["judge"]["how"]),
    ("reason", 50, lambda r: next((a["reason"] for a in r["judge"]["answers"] if a["label"] == r["judge"]["label"]),
                                  r["judge"]["answers"][0]["reason"] if r["judge"]["answers"] else "")),
    ("problems", 50, lambda r: "\n".join(next((a["problems"] for a in r["judge"]["answers"] if a["label"] == r["judge"]["label"]), []))),
    ("models", 30, lambda r: "\n".join(f"{parse_model(a['model'])[0].split('/')[-1]}: {a['label']}" for a in r["judge"]["answers"])),
    ("numbers missing", 14, lambda r: ", ".join(r["signals"]["numbers_missing"])),
    ("kind", 10, lambda r: r.get("kind") or ""),
    ("original stl", 45, lambda r: r.get("original_stl") or ""),
    ("original nl", 60, lambda r: r.get("original_nl") or ""),
    ("domain", 16, lambda r: r.get("domain") or ""),
    ("license tier", 16, lambda r: r.get("license_tier") or ""),
]
JUDGE_COLUMNS = {"label", "how", "reason", "problems", "models"}   # empty while the set isn't judged
ILLEGAL_XML = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")


def write_xlsx(path: Path, sheets: dict[str, list[dict]]):
    """
    One sheet per part, with a frozen header, filters on every column and wrapped text. The reason and problems are
    those of a model that gave the final label (the first one), so they explain it.
    """
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font
    from openpyxl.utils import get_column_letter

    book = Workbook()
    book.remove(book.active)
    wrap = Alignment(wrap_text=True, vertical="top")
    for title, rows in sheets.items():
        sheet = book.create_sheet(title)
        sheet.append([header for header, _, _ in COLUMNS])
        for cell in sheet[1]:
            cell.font = Font(bold=True)
        for r in rows:
            sheet.append([ILLEGAL_XML.sub("", str(value(r))) if r["judge"] or header not in JUDGE_COLUMNS else ""
                          for header, _, value in COLUMNS])
        for i, (_, width, _) in enumerate(COLUMNS, 1):
            sheet.column_dimensions[get_column_letter(i)].width = width
        for row in sheet.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = wrap
        sheet.freeze_panes = "B2"
        sheet.auto_filter.ref = sheet.dimensions
    book.save(path)
